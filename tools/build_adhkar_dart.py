"""Writes the mobile morning/evening adhkar list from the desktop resource (one source for both apps).
Usage: python3 tools/build_adhkar_dart.py"""
import json
a = json.load(open("src/Mawaqeety.Core/Resources/adhkar.json", encoding="utf-8"))
q = lambda s: "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"
out = []
for d in a:
    args = []
    if d.get("quran"):
        args.append("quran: [" + ", ".join(f"({x[0]}, {x[1]}, {x[2]})" for x in d["quran"]) + "]")
    if d.get("basmala"):
        args.append("basmala: true")
    if d.get("morning") is not None:
        args.append("morning: " + q(d["morning"]))
    if d.get("evening") is not None:
        args.append("evening: " + q(d["evening"]))
    args.append(f"count: {d['count']}")
    args.append("source: " + q(d["source"]))
    if d.get("virtue"):
        args.append("virtue: " + q(d["virtue"]))
    out.append("  Dhikr(\n    " + ",\n    ".join(args) + ",\n  ),")
p = "mobile/lib/data/adhkar.dart"
s = open(p, encoding="utf-8").read()
head = s[: s.index("const adhkar = <Dhikr>[")]
open(p, "w", encoding="utf-8").write(head + "// Generated by tools/build_adhkar_dart.py from src/Mawaqeety.Core/Resources/adhkar.json.\nconst adhkar = <Dhikr>[\n" + "\n".join(out) + "\n];\n")
print(len(out), "adhkar")
