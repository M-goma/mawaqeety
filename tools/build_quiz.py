#!/usr/bin/env python3
"""Builds mobile/assets/data/quiz.json: short multiple-choice quizzes made only from the app's own content.

Every question points back to the item it comes from ("ref"), and carries a proof ("p"): a phrase that must
appear in that item's text (diacritics and letter forms ignored). The script refuses to write the file if a proof
is missing from its source, if an option repeats, or if a reference does not resolve. Questions on the Qur'an
(Makki/Madani, number of ayat, order) are generated from quran.json and checked structurally instead ("k").

Output is deterministic (fixed seed). Run from the repository root:  python3 tools/build_quiz.py
mobile/test/quiz_test.dart re-checks the same rules against the bundled data.
"""
import json
import random
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / 'mobile' / 'assets' / 'data'
LIB = ROOT / 'mobile' / 'lib' / 'data'
rng = random.Random(1447)

_MARKS = re.compile('[ؐ-ًؚ-ٰٟۖ-ۭـ]')


def norm(s: str) -> str:
    """Same as Arabic.normalize in mobile/lib/core/arabic.dart."""
    s = _MARKS.sub('', s)
    s = re.sub('[أإآٱ]', 'ا', s)
    return s.replace('ى', 'ي').replace('ة', 'ه').replace('ؤ', 'و').replace('ئ', 'ي').lower().strip()


def digits(n) -> str:
    return ''.join('٠١٢٣٤٥٦٧٨٩'[int(c)] if c.isdigit() else c for c in str(n))


def load(name):
    return json.loads((DATA / name).read_text(encoding='utf-8'))


# ---------------------------------------------------------------- sources and their searchable text
prophets = {p['id']: p for p in load('prophets.json')}
ghazawat = {g['id']: g for g in load('ghazawat.json')['items']}
companions = {c['id']: c for c in load('companions.json')['companions']}
arbaeen = {h['n']: h for h in load('arbaeen.json')['hadiths']}
fiqh = {i['id']: i for i in load('fiqh.json')['items']}
quran = {s['n']: s for s in load('quran.json')}

_asma_src = (LIB / 'asma.dart').read_text(encoding='utf-8')
asma = [(m[0], m[1], m[2] == 'true') for m in re.findall(r"\('([^']+)', '([^']+)', (true|false)\)", _asma_src)]
assert len(asma) == 99, len(asma)
asma_by = {n: (m, d) for n, m, d in asma}

_ci_src = (LIB / 'companions_islam.dart').read_text(encoding='utf-8')
_ci_src = re.sub(r"'\s*\n\s*'", '', _ci_src)  # join adjacent string literals
companions_islam = {}
for block in _ci_src.split('CompanionIslam(\n')[1:]:
    cid = re.match(r"\s*'([a-z]+)'", block).group(1)
    companions_islam[cid] = block


def item_text(ref) -> str:
    src = ref['src']
    if src == 'prophets':
        p = prophets[ref['id']]
        parts = [p['nameAr'], p['title'], p['summary'], *p['lessons'], *(a.get('note', '') for a in p['ayat'])]
        for s in p['sections']:
            parts += [s['heading'], s['body']]
    elif src == 'ghazawat':
        g = ghazawat[ref['id']]
        parts = [g[k] for k in ('name', 'date', 'place', 'muslims', 'enemy', 'result', 'summary')]
        parts += g['lessons'] + [a.get('note', '') for a in g['ayat']] + [h.get('t', '') for h in g['hadith']]
        for s in g['sections']:
            parts += [s['h'], s['p']]
    elif src == 'companions':
        c = companions[ref['id']]
        parts = [c['name'], c['title'], c['bio']]
        for s in c['situations']:
            parts += [s['title'], s['text']]
    elif src == 'companions_islam':
        parts = [companions_islam[ref['id']]]
    elif src == 'arbaeen':
        h = arbaeen[ref['n']]
        parts = [h['title'], h['narrator'], h['text'], h['takhrij'], *h.get('benefits', [])]
        if h.get('extra'):
            parts.append(h['extra'].get('text', ''))
    elif src == 'fiqh':
        i = fiqh[ref['id']]
        assert i['khilaf'] is False, f"fiqh {ref['id']} is marked khilaf"
        parts = [i['q'], *(a['text'] for a in i['answers'])]
    elif src == 'asma':
        m, _ = asma_by[ref['name']]
        parts = [ref['name'], m]
    else:
        raise KeyError(src)
    return norm('\n'.join(parts))


def _ci_name(cid):
    return re.match(r"\s*'[a-z]+',\s*'([^']+)'", companions_islam[cid]).group(1)


def source_label(ref) -> str:
    """Where the answer is in the app, shown under the explanation."""
    src = ref['src']
    if src == 'prophets':
        return f"قصص الأنبياء • {prophets[ref['id']]['nameAr']}"
    if src == 'ghazawat':
        return f"غزوات النبي ﷺ • {ghazawat[ref['id']]['name']}"
    if src == 'companions':
        return f"العشرة المبشرون بالجنة • {companions[ref['id']]['name']}"
    if src == 'companions_islam':
        return f"كيف أسلم الصحابة • {_ci_name(ref['id'])}"
    if src == 'arbaeen':
        return f"الأربعون النووية • الحديث {digits(ref['n'])}: {arbaeen[ref['n']]['title']}"
    if src == 'fiqh':
        return f"فقه العبادات • {fiqh[ref['id']]['q']}"
    if src == 'asma':
        return f"أسماء الله الحسنى • {ref['name']}"
    return f"القرآن الكريم • سورة {quran[ref['n']]['name']}"


# ---------------------------------------------------------------- question list
questions = []


def add(cat, ref, q, correct, wrong, proof, ex, kind=None):
    opts = [correct, *wrong]
    assert len(opts) == 4, (q, opts)
    assert len({norm(o) for o in opts}) == 4, ('options repeat', q, opts)
    if kind is None:
        assert norm(proof) in item_text(ref), ('proof not in source', ref, proof)
    rng.shuffle(opts)
    entry = {'cat': cat, 'q': q, 'o': opts, 'a': opts.index(correct), 'ex': ex, 'ref': ref, 'src': source_label(ref)}
    if kind is None:
        entry['p'] = proof
    else:
        entry['k'] = kind
    questions.append(entry)


def H(cat, src, key, q, correct, wrong, proof, ex):
    """A hand-written question: [key] is the item id (or number for arbaeen)."""
    ref = {'src': src, ('n' if src == 'arbaeen' else 'name' if src == 'asma' else 'id'): key}
    add(cat, ref, q, correct, wrong, proof, ex)


