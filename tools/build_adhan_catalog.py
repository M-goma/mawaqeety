"""Generates src/Mawaqeety.Core/Audio/AdhanCatalog.Generated.cs from tools/adhan_files.tsv
(size<TAB>filename listing of github.com/Kiwifu/adhan-mp3). Very long files (>6 MB) are skipped."""
import os, re

here = os.path.dirname(__file__)
rows = [l.rstrip("\n").split("\t") for l in open(os.path.join(here, "adhan_files.tsv"), encoding="utf-8")]
files = sorted((int(s), f) for s, f in rows if f.lower().endswith(".mp3"))

# Stable ids already used by v1.1 (saved in users' settings) — must not change.
fixed = {
 "Mishary_Rashid_Alafasy_1_-_Kuwait_(مشاري_راشد_العفاسي_-_الكويت).mp3": "alafasy",
 "Ali_Ibn_Ahmad_Mala_1_-_Al_Haram_Al_Maki_(علي_بن_أحمد_ملا_-_الحرم_المكي).mp3": "makkah-mala",
 "Adhan_Al_Haram_Al_Madani_-_Al_Madinah_1_(أذان_الحرم_المدني_-_المدينة_المنورة).mp3": "madinah",
 "Adhan_Al_Aqsa_-_Jerusalem_(أذان_المسجد_الأقصى_-_القدس).mp3": "aqsa",
 "Abdulbasit_Abdusamad_1_-_Egypt_(عبد_الباسط_عبد_الصمد_-_مصر).mp3": "abdulbasit",
 "Muhammad_Refaat_-_Cairo_(محمد_رفعت_-_القاهرة).mp3": "refaat",
 "Mahmoud_Khalil_Al_Hussary_-_Cairo_(محمود_خليل_الحصري_-_القاهرة).mp3": "hussary",
 "Mohamed_Siddiq_El-Minshawi_-_Egypt_1_(محمد_صديق_المنشاوي_-_مصر).mp3": "minshawi",
 "Mahmoud_Ali_Al_Banna_-_Cairo_(محمود_علي_البنا_-_القاهرة).mp3": "banna",
 "Mustafa_Ismail_-_Egypt_(مصطفى_إسماعيل_-_مصر).mp3": "mustafa-ismail",
 "Nasser_Al_Qatami_1_-_Saudi_Arabia_(ناصر_القطامي_-_المملكة_العربية_السعودية).mp3": "qatami",
 "Mishary_Rashid_Alafasy_3_-_Fajr_Kuwait_(مشاري_راشد_العفاسي_-_فجر_الكويت).mp3": "alafasy-fajr",
 "Adhan_Fajr_Al_Haram_Al_Maki_(أذان_الفجر_الحرم_المكي).mp3": "makkah-fajr",
 "Adhan_Fajr_Al_Haram_Al_Madani_(أذان_الفجر_الحرم_المدني).mp3": "madinah-fajr",
 "Adhan_Fajr_Cairo_Egypt_(أذان_الفجر_القاهرة_مصر).mp3": "cairo-fajr",
}
featured = list(fixed.values())
no_arabic = {
 "Ali_Ibn_Ahmad_Mala_HQ.mp3": "علي بن أحمد ملا (جودة عالية)",
 "Azan_nakshabandi.mp3": "سيد النقشبندي",
 "Mohamed_Tarek_Reciting_Azan.mp3": "محمد طارق",
}

def cs(s): return s.replace("\\", "\\\\").replace('"', '\\"')

entries, ids = [], set(fixed.values())
for size, f in sorted(files, key=lambda x: x[1].lower()):
    if size > 6_000_000 or size < 60_000:
        continue
    stem = f[:-4]
    m = re.match(r"^(.*?)_\((.*)\)$", stem)
    if m:
        en, ar = m.group(1), m.group(2)
    else:
        en, ar = stem, no_arabic.get(f, stem.replace("_", " "))
    en = en.replace("_-_", " - ").replace("_", " ").strip()
    ar = ar.replace("_-_", " - ").replace("_", " ").strip()
    fajr = "fajr" in f.lower() or "فجر" in f
    if f in fixed:
        vid = fixed[f]
    else:
        vid = re.sub(r"[^a-z0-9]+", "-", en.lower()).strip("-")
        base, i = vid, 2
        while vid in ids:
            vid = f"{base}-{i}"; i += 1
        ids.add(vid)
    entries.append((vid, ar, en, f, fajr))

# Same muezzin recorded several times: number the Arabic names so the list stays readable.
from collections import Counter
counts = Counter(e[1] for e in entries)
seen = Counter()
numbered = []
for vid, ar, en, f, fajr in entries:
    if counts[ar] > 1:
        seen[ar] += 1
        ar = f"{ar} ({seen[ar]})"
    numbered.append((vid, ar, en, f, fajr))
entries = numbered

# Featured (well-known) voices first in the original order, then everything else alphabetically.
order = {v: i for i, v in enumerate(featured)}
entries.sort(key=lambda e: (order.get(e[0], 999), e[2].lower()))

out = ["// <auto-generated> by tools/build_adhan_catalog.py — do not edit by hand. </auto-generated>",
       "namespace Mawaqeety.Core.Audio;", "", "public static partial class AdhanCatalog", "{",
       f"    /// <summary>{len(entries)} recordings; the first {len(featured)} are the featured voices.</summary>",
       "    public static readonly IReadOnlyList<AdhanVoice> All =", "    ["]
for vid, ar, en, f, fajr in entries:
    out.append(f'        new("{cs(vid)}", "{cs(ar)}", "{cs(en)}", "{cs(f)}", {"true" if fajr else "false"}),')
out += ["    ];", "}", ""]
path = os.path.join(here, "..", "src", "Mawaqeety.Core", "Audio", "AdhanCatalog.Generated.cs")
open(path, "w", encoding="utf-8").write("\n".join(out))
print(len(entries), "voices,", sum(e[4] for e in entries), "fajr")
