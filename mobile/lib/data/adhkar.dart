/// Morning and evening remembrances (from "Hisn al-Muslim" and their cited sources).
/// [morning]/[evening] hold the wording for each time; null = not said at that time.
class Dhikr {
  final String? morning, evening;
  final int count;
  final String source;
  final String virtue;
  /// Qur'anic passage (surah, from, to) shown in the Uthmani script instead of [morning]/[evening].
  final List<(int, int, int)> quran;
  final bool basmala;
  const Dhikr({this.morning, this.evening, required this.count, required this.source, this.virtue = '',
      this.quran = const [], this.basmala = false});

  String? textFor(bool isMorning) => isMorning ? morning : evening;
  bool availableAt(bool isMorning) => quran.isNotEmpty || textFor(isMorning) != null;
}

